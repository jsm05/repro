"""The README results table and plots, built from result rows only (DESIGN 5.9).

Output is deterministic: no timestamps, no wall-clock numbers, fixed ordering and
number formatting, so two runs on the same rows give byte-identical files.
"""

from __future__ import annotations

from collections.abc import Sequence
from itertools import combinations

from repro.eval.metrics import (
    CEILINGS,
    ceiling_curve,
    gate_stats,
    paired,
    route_mix,
    success,
    token_stats,
    wilson,
)
from repro.eval.rows import GATE_CHECKS, ResultRow
from repro.models import InstanceOutcome

LETTER = {InstanceOutcome.REPRODUCED: "R", InstanceOutcome.WRONG_TEST: "W",
          InstanceOutcome.NO_TEST: "-", InstanceOutcome.INFRA_ERROR: "X"}


class ReportError(ValueError):
    pass


def group_rows(rows: Sequence[ResultRow]) -> dict[str, list[ResultRow]]:
    """Rows by config id. Refuses mixed config hashes and duplicate units."""
    by: dict[str, list[ResultRow]] = {}
    for r in rows:
        by.setdefault(r.config_id, []).append(r)
    for cid, group in by.items():
        hashes = sorted({r.config_hash for r in group})
        if len(hashes) > 1:
            raise ReportError(f"config {cid} has rows from different config hashes: "
                              f"{', '.join(hashes)}; results from different setups cannot "
                              "be blended")
        ids = [r.instance_id for r in group]
        dupes = sorted({i for i in ids if ids.count(i) > 1})
        if dupes:
            raise ReportError(f"config {cid} has more than one row for {', '.join(dupes)}")
        group.sort(key=lambda r: r.instance_id)
    return dict(sorted(by.items()))


def _pct(x: float | None) -> str:
    return "n/a" if x is None else f"{100 * x:.1f}%"


def _ci(ci: tuple[float, float] | None) -> str:
    return "n/a" if ci is None else f"[{100 * ci[0]:.1f}%, {100 * ci[1]:.1f}%]"


def _num(x: float | int | None, digits: int = 0) -> str:
    if x is None:
        return "n/a"
    return f"{x:,.{digits}f}"


def _usd(x: float | None) -> str:
    return "n/a" if x is None else f"${x:.4f}"


def _p(x: float) -> str:
    return f"{x:.4f}"


def _table(header: list[str], rows: list[list[str]]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return out


def ceiling_svg(curves: dict[str, list[tuple[int, int, int]]]) -> str:
    """A small, dependency-free line chart of S against the per-bug token ceiling."""
    w, h, left, bottom, top, right = 560, 300, 60, 40, 20, 150
    pw, ph = w - left - right, h - top - bottom
    n = len(CEILINGS)
    palette = ["#2563eb", "#dc2626", "#16a34a", "#9333ea", "#ea580c", "#0891b2"]

    def x(i: int) -> float:
        return left + (pw * i / (n - 1) if n > 1 else 0)

    def y(s: float) -> float:
        return top + ph * (1 - s)

    parts = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" '
             f'viewBox="0 0 {w} {h}" font-family="sans-serif" font-size="11">',
             f'<rect width="{w}" height="{h}" fill="white"/>']
    for k in range(0, 101, 25):
        yy = y(k / 100)
        parts.append(f'<line x1="{left}" y1="{yy:.1f}" x2="{left + pw}" y2="{yy:.1f}" '
                     'stroke="#e5e7eb"/>')
        parts.append(f'<text x="{left - 6}" y="{yy + 4:.1f}" text-anchor="end">{k}%</text>')
    for i, c in enumerate(CEILINGS):
        parts.append(f'<text x="{x(i):.1f}" y="{h - bottom + 16}" text-anchor="middle">'
                     f'{c // 1000}K</text>')
    parts.append(f'<text x="{left + pw / 2:.1f}" y="{h - 6}" text-anchor="middle">'
                 'per-bug token ceiling</text>')
    for j, (cid, curve) in enumerate(curves.items()):
        color = palette[j % len(palette)]
        pts = " ".join(f"{x(i):.1f},{y(k / nn if nn else 0):.1f}"
                       for i, (_, k, nn) in enumerate(curve))
        parts.append(f'<polyline points="{pts}" fill="none" stroke="{color}" '
                     'stroke-width="2"/>')
        ly = top + 14 * j + 6
        parts.append(f'<line x1="{left + pw + 12}" y1="{ly}" x2="{left + pw + 28}" y2="{ly}" '
                     f'stroke="{color}" stroke-width="2"/>')
        parts.append(f'<text x="{left + pw + 32}" y="{ly + 4}">{cid}</text>')
    parts.append("</svg>")
    return "\n".join(parts) + "\n"


def build_report(rows: Sequence[ResultRow], title: str = "Results") -> tuple[str, dict[str, str]]:
    """Markdown report and plots (name -> SVG text)."""
    groups = group_rows(rows)
    lines = [f"# {title}", "",
             "Generated by `repro report` from result rows only. Always-emit scores the best "
             "candidate whatever the gate said; gated emits only candidates that passed the "
             "online gate. N counts every instance: NO_TEST and INFRA_ERROR are failures.", ""]

    lines += ["## Success rate", ""]
    body = []
    for cid, g in groups.items():
        k, n = success(g, "always")
        kg, _ = success(g, "gated")
        counts = {o: sum(1 for r in g if r.outcome is o) for o in InstanceOutcome}
        first = g[0]
        body.append([
            f"`{cid}`", first.kind, first.logical_model, f"`{first.config_hash}`", str(n),
            str(k), f"{_pct(k / n if n else None)} {_ci(wilson(k, n))}",
            str(kg), f"{_pct(kg / n if n else None)} {_ci(wilson(kg, n))}",
            str(counts[InstanceOutcome.WRONG_TEST]), str(counts[InstanceOutcome.NO_TEST]),
            str(counts[InstanceOutcome.INFRA_ERROR]),
        ])
    lines += _table(["Config", "Kind", "Logical model", "Config hash", "N", "Reproduced",
                     "S always-emit [95% CI]", "Reproduced (gated)", "S gated [95% CI]",
                     "WRONG_TEST", "NO_TEST", "INFRA_ERROR"], body)
    lines.append("")

    pairs = []
    for a, b in combinations(groups, 2):
        p = paired(groups[a], groups[b])
        common = p.a_only + p.b_only + p.both + p.neither
        if common:
            pairs.append([f"`{a}`", f"`{b}`", str(common), str(p.a_only), str(p.b_only),
                          _p(p.p_value)])
    if pairs:
        lines += ["## Paired comparison (always-emit, exact McNemar)", ""]
        lines += _table(["A", "B", "Common instances", "A only", "B only", "p"], pairs)
        lines.append("")

    lines += ["## Gate (gated mode)", "",
              "B0 has no gate, so its gated numbers equal always-emit. Claimed = a test was "
              "emitted in gated mode.", ""]
    body = []
    for cid, g in groups.items():
        s = gate_stats(g)
        body.append([f"`{cid}`", str(s.claimed),
                     f"{_pct(s.precision)} {_ci(s.precision_ci)}", _pct(s.precision_no_gate),
                     _pct(s.recall), _pct(s.abstain_rate), _pct(s.gate_recall_cost),
                     " ".join(f"{c}:{s.rejections[c]}" for c in GATE_CHECKS)])
    lines += _table(["Config", "Claimed", "Precision [95% CI]", "Precision without gate",
                     "Recall", "Abstain rate", "Gate recall cost", "Rejections"], body)
    lines.append("")

    lines += ["## Compute", ""]
    body = []
    for cid, g in groups.items():
        t = token_stats(g)
        body.append([f"`{cid}`", _num(t.mean), _num(t.median), _num(t.p90), _num(t.max),
                     _num(t.total), _num(t.per_reproduced), _num(t.requests_mean, 1),
                     _num(t.rate_limit_wait_mean_s, 1), _usd(t.list_price_per_bug_usd),
                     _usd(t.list_price_per_reproduced_usd)])
    lines += _table(["Config", "Tokens mean", "Median", "p90", "Max", "Total",
                     "Tokens per reproduced", "Requests per bug", "Rate-limit wait per bug (s)",
                     "List price per bug", "List price per reproduced"], body)
    lines += ["", "Actual spend: $0.00 (free tiers only).", ""]

    curves = {cid: ceiling_curve(g) for cid, g in groups.items()}
    lines += ["## Token ceiling curve (always-emit)", "",
              "S if the per-bug token ceiling had been lower. A reproduction counts only if its "
              "candidate existed before cumulative tokens crossed the ceiling.", ""]
    body = [[f"`{cid}`"] + [f"{k}/{n} ({_pct(k / n if n else None)})" for _, k, n in curve]
            for cid, curve in curves.items()]
    lines += _table(["Config"] + [f"{c // 1000}K" for c in CEILINGS], body)
    lines += ["", "![Token ceiling curve](plots/token_ceiling.svg)", ""]

    lines += ["## Route mix", ""]
    body = []
    for cid, g in groups.items():
        m = route_mix(g)
        for route, calls in m.calls.items():
            body.append([f"`{cid}`", f"`{route}`", str(calls), _pct(m.share[route])])
        body.append([f"`{cid}`", "retries / deferrals / mixed rows", "",
                     f"{m.retries} / {m.deferrals} / {m.mixed_rows}"])
    lines += _table(["Config", "Route", "Calls", "Share"], body)
    lines.append("")

    lines += ["## Per instance", "",
              "R reproduced, W wrong test, - no test, X infra error; always-emit / gated.", ""]
    instances = sorted({r.instance_id for g in groups.values() for r in g})
    by_key = {(r.config_id, r.instance_id): r for g in groups.values() for r in g}
    body = []
    for iid in instances:
        cells = [f"`{iid}`"]
        for cid in groups:
            r = by_key.get((cid, iid))
            cells.append(f"{LETTER[r.outcome]} / {LETTER[r.outcome_gated]}" if r else "")
        body.append(cells)
    lines += _table(["Instance"] + [f"`{c}`" for c in groups], body)
    lines.append("")
    return "\n".join(lines), {"token_ceiling.svg": ceiling_svg(curves)}
